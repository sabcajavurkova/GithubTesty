package org.example;

public class Matematik {
    int x;
    int y;

    public Matematik (int x, int y) {
        this.x = x;
        this.y =y;
    }

    public int secti() {
        return x + y;
    }

    public int odecti() {
        return x - y;
    }

    public int vynasob() {
        return x * y;
    }
}
